// PIXTION · scripts/build.mjs — regenerates sw.js so offline mode always has the latest files.
// Run after changing any file:   node scripts/build.mjs
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = join(fileURLToPath(import.meta.url), '..', '..');
const SKIP = new Set(['scripts', 'node_modules', '.git', 'sw.js', 'vercel.json', '.vercelignore', 'README.md', 'robots.txt', 'sitemap.xml']);
const SKIP_EXT = ['.zip', '.txt', '.map'];
const SKIP_FILES = new Set(['assets/og-image.png']);

function walk(dir) {
  return readdirSync(dir).flatMap(name => {
    if (SKIP.has(name)) return [];
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return walk(full);
    const rel = relative(ROOT, full).split(sep).join('/');
    if (SKIP_FILES.has(rel) || SKIP_EXT.some(e => rel.endsWith(e))) return [];
    return [rel];
  });
}

const files = walk(ROOT).sort();
const hash = createHash('sha256');
for (const f of files) { hash.update(f); hash.update(readFileSync(join(ROOT, f))); }
const version = hash.digest('hex').slice(0, 10);
const core = ['./', ...files.map(f => './' + f)];

const sw = `/* PIXTION · sw.js — offline support. GENERATED by scripts/build.mjs, do not edit by hand. */
const CACHE = 'pixtion-${version}';
const CORE = ${JSON.stringify(core, null, 2)};

self.addEventListener('install', event => {
  self.skipWaiting();
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(CORE)));
});

self.addEventListener('activate', event => {
  event.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith('pixtion-') && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener('fetch', event => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    // Pages: fresh from the network when online, cached copy when offline.
    event.respondWith(fetch(req).then(res => {
      const copy = res.clone(); caches.open(CACHE).then(c => c.put('./', copy));
      return res;
    }).catch(() => caches.match('./')));
    return;
  }
  // Files: cached copy first (fast, works offline), network as fallback.
  event.respondWith(caches.match(req).then(hit => hit || fetch(req).then(res => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }
    return res;
  })));
});
`;
writeFileSync(join(ROOT, 'sw.js'), sw);
console.log(`sw.js written: ${files.length} files, cache pixtion-${version}`);
